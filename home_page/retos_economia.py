def _mes_largo(clave):
    """'2026-10' → 'octubre de 2026'."""
    anio, mes = clave.split('-')
    return f'{MESES[int(mes) - 1]} de {anio}'


def _ultimo(serie):
    clave = max(serie)
    return clave, serie[clave]


def _miles(valor):
    """3461.92 → '3.462' (separador de miles al estilo de Colombia)."""
    return f'{round(valor):,}'.replace(',', '.')


def _trimestre(clave):
    """'2026-Q3' → 'tercer trimestre de 2026'."""
    anio, t = clave.split('-Q')
    return f'{("primer", "segundo", "tercer", "cuarto")[int(t) - 1]} trimestre de {anio}'


def resumen():
    """Cifras de los textos de las gráficas, ya con coma decimal."""
    mes_fao, fao = _ultimo(FAO_FFPI)
    anio, mes = mes_fao.split('-')
    fao_hace_un_anio = FAO_FFPI[f'{int(anio) - 1}-{mes}']
    pico_fao = max(FAO_FFPI, key=FAO_FFPI.get)

    inflacion = {k: _ultimo(v) for k, v in INFLACION.items()}
    col = INFLACION['colombia']
    tasas = {k: _ultimo(v) for k, v in TASAS.items()}

    pico_trm = max(TRM_MENSUAL, key=TRM_MENSUAL.get)
    fecha_trm = TRM_ULTIMA['fecha']

    medido = DEUDA_PRIMER_ANIO_PROYECTADO - 1
    final = max(DEUDA_PIB['mundo'])

    anio_int = max(INTERESES_VS_DEFENSA)
    primero_mayor = min(a for a, v in INTERESES_VS_DEFENSA.items() if v['intereses'] > v['defensa'])

    anio_ar = max(ARANCEL_EFECTIVO_ANUAL)
    valor_ar = ARANCEL_EFECTIVO_ANUAL[anio_ar]
    desde = max(a for a, v in ARANCEL_EFECTIVO_ANUAL.items() if a < anio_ar and v >= valor_ar)
    pico_trim = max(ARANCEL_EFECTIVO_TRIMESTRAL, key=ARANCEL_EFECTIVO_TRIMESTRAL.get)
    ultimo_trim = max(ARANCEL_EFECTIVO_TRIMESTRAL)
    maximo_ar = max(ARANCEL_EFECTIVO_ANUAL, key=ARANCEL_EFECTIVO_ANUAL.get)

    return {
        'fao_mes': _mes_largo(mes_fao),
        'fao_valor': _coma(fao, 1),
        'fao_interanual': _coma(abs(fao / fao_hace_un_anio - 1) * 100, 1),
        'fao_sube': fao > fao_hace_un_anio,
        'fao_pico_mes': _mes_largo(pico_fao),
        'fao_pico': _coma(FAO_FFPI[pico_fao], 1),
        'fao_bajo_pico': _coma((1 - fao / FAO_FFPI[pico_fao]) * 100, 0),

        'inflacion': {k: {'mes': _mes_largo(m), 'valor': _coma(v, 1)} for k, (m, v) in inflacion.items()},
        'inflacion_pico_col': _coma(max(col.values()), 1),
        'inflacion_pico_col_mes': _mes_largo(max(col, key=col.get)),

        'tasas': {k: _coma(v, 2) for k, (m, v) in tasas.items()},

        'trm_valor': _miles(TRM_ULTIMA['valor']),
        'trm_fecha': f'{int(fecha_trm[8:])} de {MESES[int(fecha_trm[5:7]) - 1]} de {fecha_trm[:4]}',
        'trm_pico': _miles(TRM_MENSUAL[pico_trm]),
        'trm_pico_mes': _mes_largo(pico_trm),

        'deuda_anio': medido,
        'deuda': {k: _coma(v[medido], 0) for k, v in DEUDA_PIB.items()},
        'deuda_anio_final': final,
        'deuda_final': {k: _coma(v[final], 0) for k, v in DEUDA_PIB.items()},

        'int_anio': anio_int,
        'int_intereses': _miles(INTERESES_VS_DEFENSA[anio_int]['intereses']),
        'int_defensa': _miles(INTERESES_VS_DEFENSA[anio_int]['defensa']),
        'int_primero': primero_mayor,
        'int_inicio_anio': min(INTERESES_VS_DEFENSA),
        'int_inicio': _miles(INTERESES_VS_DEFENSA[min(INTERESES_VS_DEFENSA)]['intereses']),

        'ar_anio': anio_ar,
        'ar_valor': _coma(valor_ar, 1),
        'ar_anterior': _coma(ARANCEL_EFECTIVO_ANUAL[anio_ar - 1], 1),
        'ar_desde': desde,
        'ar_pico_trim': _trimestre(pico_trim),
        'ar_pico_trim_valor': _coma(ARANCEL_EFECTIVO_TRIMESTRAL[pico_trim], 1),
        'ar_ultimo_trim': _trimestre(ultimo_trim),
        'ar_ultimo_trim_valor': _coma(ARANCEL_EFECTIVO_TRIMESTRAL[ultimo_trim] + 1e-9, 1),  # 6,85 → 6,9, no 6,8
        'ar_maximo': _coma(ARANCEL_EFECTIVO_ANUAL[maximo_ar], 1),
        'ar_maximo_anio': maximo_ar,
    }


def _alinear(series, claves):
    """Cada serie como lista sobre las mismas claves, con None donde le falte el dato."""
    return {k: [v.get(c) for c in claves] for k, v in series.items()}


def contexto():
    meses_inf = sorted(set().union(*INFLACION.values()))
    meses_tasas = sorted(set().union(*TASAS.values()))
    anios_deuda = sorted(set().union(*DEUDA_PIB.values()))
    return {
        'resumen': resumen(),
        'info': INFO_GRAFICAS,
        'datos_graficas': {
            'retos-alimentos': {'meses': list(FAO_FFPI), 'valores': list(FAO_FFPI.values())},
            'retos-inflacion': {'meses': meses_inf, **_alinear(INFLACION, meses_inf)},
            'retos-tasas': {'meses': meses_tasas, **_alinear(TASAS, meses_tasas)},
            'retos-trm': {'meses': list(TRM_MENSUAL), 'valores': list(TRM_MENSUAL.values())},
            'retos-deuda': {
                'anios': anios_deuda,
                'primer_proyectado': DEUDA_PRIMER_ANIO_PROYECTADO,
                **_alinear(DEUDA_PIB, anios_deuda),
            },
            'retos-intereses': {
                'anios': list(INTERESES_VS_DEFENSA),
                'intereses': [v['intereses'] for v in INTERESES_VS_DEFENSA.values()],
                'defensa': [v['defensa'] for v in INTERESES_VS_DEFENSA.values()],
            },
            'retos-aranceles': {
                'anios': list(ARANCEL_EFECTIVO_ANUAL),
                'valores': list(ARANCEL_EFECTIVO_ANUAL.values()),
            },
        },
    }
